#[test]
fn macro_functions_match_the_linux_expansions() {
    // MI_LOAD_REGISTER_IMM(x) = MI_INSTR(0x22, 2*x-1): x=1 -> 0x11000001, x=3 -> 0x11000005 (intel_gpu_commands.h:155)
    assert_eq!(mi_load_register_imm(1), 0x1100_0001);
    assert_eq!(mi_load_register_imm(3), 0x1100_0005);
    assert_eq!(mi_load_register_imm(2), 0x1100_0003);
    // GFX_OP_PIPE_CONTROL(6) = 0x7a000004 (the gen8+ six-dword pipe control header, intel_gpu_commands.h:287)
    assert_eq!(gfx_op_pipe_control(6), 0x7a00_0004);
    assert_eq!(gfx_op_pipe_control(5), 0x7a00_0003);
    assert_eq!(mi_instr(0x08, 0), 0x0400_0000);
    assert_eq!(mi_opcode(MI_LOAD_REGISTER_IMM_HEADER), 0x22);
    assert!(is_mi_lri_cmd(mi_load_register_imm(5)));
    assert!(!is_mi_lri_cmd(MI_NOOP));
    assert_eq!(mi_lri_len(mi_load_register_imm(2)), 4);
    assert_eq!(mi_semaphore_target(1), 1 << 15);
    assert_eq!(mi_display_flip_plane(1), 1 << 20);
    assert_eq!(gfx_instr(0x1d, 0x10), 0x7d00_0010);
    assert_eq!(instr(INSTR_RC_CLIENT), 0x6000_0000);
}

const MI_LOAD_REGISTER_IMM_HEADER: u32 = 0x1100_0001;

#[test]
fn zero_valued_constants_are_pinned_by_behaviour() {
    // MI_ARB_DISABLE == 0 (intel_gpu_commands.h:61): selecting it must differ from selecting MI_ARB_ENABLE.
    assert_ne!(MI_ARB_ON_OFF | MI_ARB_DISABLE, MI_ARB_ON_OFF | MI_ARB_ENABLE);
    assert_ne!(MI_SEMAPHORE_SAD_GT_SDD, MI_SEMAPHORE_SAD_GTE_SDD);
    assert_ne!(MI_FLUSH_DW_USE_PPGTT, MI_FLUSH_DW_USE_GTT);
    assert_ne!(MI_MM_SPACE_PHYSICAL, MI_MM_SPACE_GTT);
    assert_ne!(MI_DISPLAY_FLIP_IVB_PLANE_A, MI_DISPLAY_FLIP_IVB_PLANE_B);
    assert_ne!(BLT_DEPTH_8, BLT_DEPTH_16_565);
    assert_ne!(MI_OVERLAY_CONTINUE, MI_OVERLAY_ON);
}

