#!/usr/bin/env python3
# Generates src/regs.rs (values evaluated here) and tests/header_values.rs (values evaluated by gcc over the SAME macro text);
# the two evaluators must agree or generation stops. Usage: gen_consts.py <linux-ref>
import re,os,subprocess,sys,tempfile
LIN=sys.argv[1] if len(sys.argv)>1 else os.path.expanduser("~/Projects/references/coralos/linux-ref")
OUT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))+"/"
HDR=LIN+"/include/sound/hda_register.h"
lines=open(HDR).read().split("\n")
defs=[];i=0
while i<len(lines):
    m=re.match(r'#define\s+([A-Za-z_]\w*)(\(.*?\))?\s+(.*)$',lines[i])
    if m:
        start=i+1;name,fn,expr=m.group(1),m.group(2),m.group(3)
        while expr.rstrip().endswith("\\"):
            i+=1;expr=expr.rstrip()[:-1]+" "+lines[i].strip()
        expr=re.sub(r'/\*.*?\*/','',expr).strip()
        defs.append((name,fn,expr,start))
    i+=1
ns={"HDA_MAX_CODECS":8}
BIT=lambda n:1<<n
GENMASK=lambda h,l:((1<<(h+1))-1)&~((1<<l)-1)
fns={"BIT":BIT,"GENMASK":GENMASK,"AZX_REG_MASK":lambda b,o:((1<<b)-1)<<o}
vals=[]
for name,fn,expr,ln in defs:
    if fn or not expr: continue
    try: v=eval(expr,{"__builtins__":{}},{**ns,**fns})
    except Exception: continue
    if not isinstance(v,int): continue
    v&=0xffffffff if v<0 else v
    if name in ns: continue  # a name defined twice with the same value (AZX_REG_LLCH, hda_register.h:33 and :97): keep the first
    ns[name]=v;vals.append((name,expr,ln,v))
# gcc over the same text
c=["#include <stdio.h>","#define BIT(n) (1UL << (n))","#define GENMASK(h,l) (((~0UL) << (l)) & (~0UL >> (63 - (h))))","#define HDA_MAX_CODECS 8"]
for name,fn,expr,ln in defs:
    if name in ("HDA_MAX_CODECS",): continue
    if fn: c.append(f"#define {name}{fn} {expr}")
    else: c.append(f"#define {name} {expr}")
c.append("int main(void){")
for name,expr,ln,v in vals: c.append(f'printf("%s %llu\\n","{name}",(unsigned long long)(unsigned int)({name}));')
c.append("return 0;}")
d=tempfile.mkdtemp()
open(d+"/dump.c","w").write("\n".join(c))
subprocess.check_call(["gcc","-w","-o",d+"/dump",d+"/dump.c"])
g={l.split()[0]:int(l.split()[1]) for l in subprocess.check_output([d+"/dump"]).decode().split("\n") if l}
for name,expr,ln,v in vals:
    assert g[name]==v&0xffffffff,(name,g[name],v)
src=["// SPDX-License-Identifier: GPL-2.0-only","//! HD-audio controller registers and bit fields of `include/sound/hda_register.h` (Linux v7.0-rc6), every one with its LINE.","// GENERATED by tools/gen_consts.py (values evaluated from the macro text and cross-checked against gcc at generation time; the","// test file carries the gcc values, which do not pass through this table). All are 32-bit; offsets are relative to the window the","// name says (controller BAR0, a capability, a stream descriptor, a link).",""]
for name,expr,ln,v in vals:
    src.append(f"pub const {name}: u32 = {v:#x}; // hda_register.h:{ln}")
open(OUT+"src/regs.rs","w").write("\n".join(src)+"\n")
t=["// SPDX-License-Identifier: GPL-2.0-only","//! Every constant of `hda_register.h` against the value gcc computes from the Linux macro text (BIT/GENMASK shimmed), written out literally.","use hda_ext_core::regs::*;","","#[test]","fn hda_register_constants_equal_the_values_gcc_computes_from_the_linux_header() {"]
for name,expr,ln,v in vals: t.append(f'    assert_eq!({name}, {g[name]:#x}, "{name}");')
t.append("}")
open(OUT+"tests/header_values.rs","w").write("\n".join(t)+"\n")
print(len(vals))
