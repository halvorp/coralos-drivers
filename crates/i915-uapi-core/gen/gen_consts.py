# Mechanical extraction of the #define constants this crate carries from Linux include/uapi/drm/i915_drm.h (v7.0-rc6) into
# src/consts.rs, each with its header line. Run: python3 -I gen/gen_consts.py <path-to-i915_drm.h> > src/consts.rs
# The tests (tests/consts.rs) pin the values BY HAND against the header, so a wrong extraction cannot pass.
import re, sys
H = sys.argv[1]
lines = open(H).read().split("\n")
defs = {}
for i, l in enumerate(lines, 1):
    m = re.match(r'\s*#define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.*?)\s*(/\*.*)?$', l)
    if m:
        defs.setdefault(m.group(1), (i, m.group(2).strip()))

def conv(e):
    e = re.sub(r'\b(0x[0-9a-fA-F]+|\d+)(ul|UL|u|U)\b', r'\1', e.strip())
    while e.startswith('(') and e.endswith(')') and e.count('(') == 1:
        e = e[1:-1].strip()
    return e

def pick(prefixes=(), names=(), exclude=()):
    out = []
    for n, (ln, ex) in defs.items():
        if n in exclude or ex.startswith('\\') or ex == '' or n.endswith(')'):
            continue
        if n in names or any(n.startswith(p) for p in prefixes):
            out.append((ln, n, conv(ex)))
    out.sort()
    return out

CMD = ["DRM_I915_GETPARAM","DRM_I915_SETPARAM","DRM_I915_REG_READ","DRM_I915_GET_RESET_STATS","DRM_I915_QUERY",
       "DRM_I915_PERF_OPEN","DRM_I915_PERF_ADD_CONFIG","DRM_I915_PERF_REMOVE_CONFIG"]
groups = [
 ("param", "u32", "`I915_PARAM_*`: the GETPARAM selectors (i915_drm.h:597-813).", pick(["I915_PARAM_"])),
 ("cmd", "u32", "`DRM_I915_*` command numbers (the offset past DRM_COMMAND_BASE; i915_drm.h:428-487).",
   [r for r in pick(["DRM_I915_GEM_"], CMD, ["DRM_I915_GEM_EXECBUFFER_EXT_TIMELINE_FENCES"]) if not r[1].startswith("DRM_I915_QUERY_")]),
 ("exec", "u64", "`drm_i915_gem_execbuffer2::flags` (i915_drm.h:1431-1549).", pick(["I915_EXEC_"], [], ["I915_EXEC_CONTEXT_ID_MASK","I915_EXEC_FENCE_WAIT","I915_EXEC_FENCE_SIGNAL"])),
 ("exec_object", "u64", "`drm_i915_gem_exec_object2::flags` (i915_drm.h:1273-1306).", pick(["EXEC_OBJECT_"], [], ["EXEC_OBJECT_PAD_TO_SIZE_X"])),
 ("exec_fence", "u32", "`drm_i915_gem_exec_fence::flags` (i915_drm.h:1341-1342) and the timeline-fences extension name (:1356).",
   pick([], ["I915_EXEC_FENCE_WAIT","I915_EXEC_FENCE_SIGNAL","DRM_I915_GEM_EXECBUFFER_EXT_TIMELINE_FENCES"])),
 ("domain", "u32", "`I915_GEM_DOMAIN_*` (i915_drm.h:1171-1185).", pick(["I915_GEM_DOMAIN_"])),
 ("ctx_param", "u64", "`drm_i915_gem_context_param::param` selectors (i915_drm.h:1999-2174).", pick(["I915_CONTEXT_PARAM_"])),
 ("query", "u32", "`drm_i915_query_item::query_id` and the perf-config sub-ids (i915_drm.h:3071-3108).", pick(["DRM_I915_QUERY_"])),
 ("misc", "u32", "Scheduler caps, mmap/caching/tiling/madvise modes, context-create and GEM-create extensions, engine-info flags.",
   pick(["I915_SCHEDULER_CAP_","I915_MMAP_","I915_CACHING_","I915_TILING_","I915_BIT_6_SWIZZLE_","I915_MADV_","I915_CONTEXT_CREATE_",
         "I915_CONTEXT_ENGINES_EXT_","I915_USERPTR_","I915_GEM_CREATE_EXT_","I915_ENGINE_INFO_","I915_VIDEO_","I915_CONTEXT_MAX_USER_PRIORITY",
         "I915_CONTEXT_DEFAULT_PRIORITY","I915_CONTEXT_MIN_USER_PRIORITY"], ["I915_REG_READ_8B_WA"], ["I915_CONTEXT_CREATE_FLAGS_UNKNOWN"])),
]
print("// SPDX-License-Identifier: GPL-2.0-only")
print("//! GENERATED by gen/gen_consts.py from Linux include/uapi/drm/i915_drm.h (v7.0-rc6). Do not edit by hand: re-run the generator.")
print("//! Original copyright: Intel Corporation and the i915 authors. Every constant carries its header line; tests/consts.rs pins the")
print("//! values by hand against the header.")
print("#![allow(clippy::identity_op, clippy::erasing_op)]")
seen = set()
for g, ty, doc, rows in groups:
    print(f"\n/// {doc}\npub mod {g} {{")
    for ln, n, ex in rows:
        if n in seen: continue
        seen.add(n)
        t = ty
        if n == "I915_USERPTR_UNSYNCHRONIZED": t = "u32"
        if n in ("I915_CONTEXT_MAX_USER_PRIORITY","I915_CONTEXT_DEFAULT_PRIORITY","I915_CONTEXT_MIN_USER_PRIORITY"): t = "i32"
        print(f"    pub const {n}: {t} = {ex}; // i915_drm.h:{ln}")
    print("}")
